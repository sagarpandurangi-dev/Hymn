def _refined(category: str, keyword: str) -> str:
    rules = _REFINE.get(category)
    if not rules:
        return category
    for fine, text in rules.items():
        if fine != "_default" and keyword in {" ".join(w.split()) for w in text.split(",")}:
            return fine
    return rules.get("_default", category)


def _keywords() -> List[Tuple[Tuple[str, ...], str]]:
    items = []
    for category, text in _DIRECTORY.items():
        for raw in text.split(","):
            words = tuple(raw.split())
            if words:
                items.append((words, _refined(category, " ".join(words))))
    # Longer, more specific keywords first ("SWIGGY INSTAMART" before "SWIGGY").
    items.sort(key=lambda kc: (-len(" ".join(kc[0])), " ".join(kc[0])))
    return items


KEYWORDS = _keywords()
_SPLIT = re.compile(r"[^A-Z0-9]+")


def _word_matches(keyword: str, word: str) -> bool:
    if len(keyword) <= 4:
        return word == keyword or (word.startswith(keyword) and word[len(keyword):].isdigit())
    return word.startswith(keyword)


def lookup(description: str) -> Optional[Tuple[str, str]]:
    """(category, keyword) for a known merchant in this description, else None."""
    words = [w for w in _SPLIT.split((description or "").upper()) if w]
    for keyword, category in KEYWORDS:
        n = len(keyword)
        for i in range(len(words) - n + 1):
            # Inner words of a phrase must match exactly; the last may run on.
            if all(words[i + j] == keyword[j] for j in range(n - 1)) and _word_matches(keyword[-1], words[i + n - 1]):
                return category, " ".join(keyword)
    return None
